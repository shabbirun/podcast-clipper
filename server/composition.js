// Generates the HyperFrames project files for a clip:
//   index.html     – the composition (static; reads window.CLIP_DATA at init)
//   clip-data.js   – generated from clip.json on every save (captions, layout, hook)
//   captions.srt   – human-readable export of the caption cues
//
// index.html is written once so any hand edits made in HyperFrames Studio
// survive caption edits made in the app.

export const CAPTION_STYLES = {
  bold: "Bold (white + yellow highlight)",
  box: "Box (white text on dark pill)",
  minimal: "Minimal (clean white)",
  karaoke: "Karaoke (dim → bright words)",
};

export function defaultSettings({ hook }) {
  return {
    layout: "crop", // crop = fill 9:16, fit = full 16:9 frame over blurred fill
    focusX: 0.5, // crop: horizontal focus 0 (left) … 1 (right)
    zoom: 1,
    captions: {
      enabled: true,
      style: "bold",
      positionY: 68, // % from top
      fontSize: 78,
      uppercase: true,
      highlight: "#FFE14D",
      maxWordsPerCue: 4,
    },
    hook: {
      enabled: Boolean(hook),
      text: hook || "",
      duration: 3.5,
    },
  };
}

/** Group clip-relative words into short caption cues. */
export function wordsToCues(words, maxWords = 4) {
  const cues = [];
  let cur = null;
  for (const w of words) {
    const gap = cur ? w.start - cur.end : 0;
    const full = cur && (cur.words.length >= maxWords || cur.end - cur.start > 1.8);
    const breakPunct = cur && /[.?!,;:]$/.test(cur.words[cur.words.length - 1].text) && cur.words.length >= 2;
    if (!cur || gap > 0.6 || full || breakPunct) {
      if (cur) cues.push(cur);
      cur = { start: w.start, end: w.end, words: [w] };
    } else {
      cur.end = w.end;
      cur.words.push(w);
    }
  }
  if (cur) cues.push(cur);
  // Hold each cue until the next one starts if the gap is small.
  for (let i = 0; i < cues.length - 1; i++) {
    if (cues[i + 1].start - cues[i].end < 0.4) cues[i].end = cues[i + 1].start;
  }
  return cues.map((c) => ({
    start: r(c.start),
    end: r(c.end),
    text: c.words.map((w) => w.text).join(" "),
    words: c.words.map((w) => ({ start: r(w.start), end: r(w.end), text: w.text })),
  }));
}

const r = (n) => Math.round(n * 1000) / 1000;

function srtTime(s) {
  const ms = Math.max(0, Math.round(s * 1000));
  const h = Math.floor(ms / 3600000);
  const m = Math.floor((ms % 3600000) / 60000);
  const sec = Math.floor((ms % 60000) / 1000);
  const pad = (n, l = 2) => String(n).padStart(l, "0");
  return `${pad(h)}:${pad(m)}:${pad(sec)},${pad(ms % 1000, 3)}`;
}

export function cuesToSrt(cues) {
  return cues
    .map((c, i) => `${i + 1}\n${srtTime(c.start)} --> ${srtTime(c.end)}\n${c.text}\n`)
    .join("\n");
}

export function srtToCues(srt) {
  const toSec = (t) => {
    const [h, m, rest] = t.trim().replace(".", ",").split(":");
    const [s, ms] = rest.split(",");
    return Number(h) * 3600 + Number(m) * 60 + Number(s) + Number(ms || 0) / 1000;
  };
  const cues = [];
  for (const block of srt.replace(/\r/g, "").split(/\n\s*\n/)) {
    const lines = block.split("\n").filter((l) => l.trim() !== "");
    const ti = lines.findIndex((l) => l.includes("-->"));
    if (ti < 0) continue;
    const [a, b] = lines[ti].split("-->");
    const text = lines.slice(ti + 1).join(" ").trim();
    if (!text) continue;
    cues.push({ start: r(toSec(a)), end: r(toSec(b)), text });
  }
  return cues;
}

export function clipDataJs(clip, data) {
  const payload = {
    duration: clip.duration,
    source: data.source, // { width, height }
    ...data.settings,
    cues: data.cues,
  };
  return `// Generated by podcast-clipper from clip.json — edit captions in the app.\nwindow.CLIP_DATA = ${JSON.stringify(payload, null, 2)};\n`;
}

export function indexHtml(clip) {
  const D = clip.duration.toFixed(3);
  const title = clip.title.replace(/[<>&"]/g, "");
  return `<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>${title}</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Montserrat:wght@700;800;900&display=block" rel="stylesheet" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="clip-data.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1080px; height: 1920px; overflow: hidden; background: #000; }
      #root { position: relative; width: 1080px; height: 1920px; overflow: hidden; font-family: Montserrat, Inter, system-ui, sans-serif; }
      #backdrop { position: absolute; inset: 0; background: #0b0b0b; }
      #bg-video { position: absolute; left: -10%; top: -10%; width: 120%; height: 120%; object-fit: cover; filter: blur(48px) brightness(0.55) saturate(1.2); }
      #main-video { position: absolute; left: 0; top: 0; width: 1080px; height: 1920px; object-fit: cover; }
      .layer { position: absolute; inset: 0; pointer-events: none; }

      /* Hook */
      #hook-text { position: absolute; left: 50%; top: 230px; width: max-content; max-width: 940px; background: #fff; color: #0b0b0b; font-weight: 900; font-size: 62px; line-height: 1.12; text-align: center; padding: 26px 36px; border-radius: 26px; box-shadow: 0 18px 50px rgba(0,0,0,0.45); opacity: 0; visibility: hidden; }

      /* Captions */
      .cue { position: absolute; left: 60px; right: 60px; display: flex; flex-wrap: wrap; justify-content: center; align-items: center; gap: 0 0.28em; text-align: center; line-height: 1.12; opacity: 0; visibility: hidden; transform-origin: 50% 50%; }
      .cue .w { display: inline-block; }
      .style-bold .cue { color: #fff; font-weight: 900; -webkit-text-stroke: 10px #000; paint-order: stroke fill; text-shadow: 0 8px 24px rgba(0,0,0,0.55); }
      .style-box .cue { font-weight: 800; }
      .style-box .cue-inner { display: flex; flex-wrap: wrap; justify-content: center; gap: 0 0.28em; background: rgba(10,10,10,0.82); color: #fff; padding: 18px 30px; border-radius: 22px; }
      .style-minimal .cue { color: #fff; font-weight: 700; text-shadow: 0 4px 18px rgba(0,0,0,0.75); }
      .style-karaoke .cue { color: rgba(255,255,255,0.45); font-weight: 900; -webkit-text-stroke: 8px rgba(0,0,0,0.85); paint-order: stroke fill; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${D}" data-width="1080" data-height="1920">
      <div id="backdrop" class="clip" data-start="0" data-duration="${D}" data-track-index="0"></div>
      <video id="bg-video" class="clip" src="assets/clip-bg.mp4" data-start="0" data-duration="${D}" data-track-index="1" muted playsinline></video>
      <video id="main-video" class="clip" src="assets/clip.mp4" data-start="0" data-duration="${D}" data-track-index="2" muted playsinline></video>
      <audio id="main-audio" src="assets/clip.mp4" data-start="0" data-duration="${D}" data-track-index="10" data-volume="1"></audio>
      <div id="hook" class="clip layer" data-start="0" data-duration="${D}" data-track-index="3"><span id="hook-text"></span></div>
      <div id="caption-layer" class="clip layer" data-start="0" data-duration="${D}" data-track-index="4"></div>
    </div>
    <script>
      (function () {
        const data = window.CLIP_DATA || { cues: [], captions: { enabled: false }, hook: { enabled: false } };
        const W = 1080, H = 1920, D = ${D};
        const srcAspect = data.source && data.source.width ? data.source.width / data.source.height : 16 / 9;

        // Layout: crop fills the frame with a horizontal focus; fit shows the full frame over a blurred fill.
        const main = document.getElementById("main-video");
        const bg = document.getElementById("bg-video");
        const zoom = data.zoom || 1;
        if (data.layout === "fit") {
          const w = W * zoom, h = w / srcAspect;
          Object.assign(main.style, { width: w + "px", height: h + "px", left: (W - w) / 2 + "px", top: (H - h) / 2 + "px" });
        } else {
          bg.style.opacity = "0";
          const h = H * zoom, w = h * srcAspect;
          const fx = data.focusX == null ? 0.5 : data.focusX;
          Object.assign(main.style, { width: w + "px", height: h + "px", left: -(w - W) * fx + "px", top: -(h - H) / 2 + "px" });
        }

        const tl = gsap.timeline({ paused: true });

        // Hook text
        const hook = data.hook || {};
        if (hook.enabled && hook.text) {
          document.getElementById("hook-text").textContent = hook.text;
          const out = Math.min(hook.duration || 3.5, D - 0.3);
          tl.fromTo("#hook-text", { autoAlpha: 0, xPercent: -50, x: 0, y: -30, scale: 0.92 }, { autoAlpha: 1, y: 0, scale: 1, duration: 0.45, ease: "back.out(1.8)" }, 0.15);
          tl.to("#hook-text", { autoAlpha: 0, y: -20, duration: 0.3, ease: "power2.in" }, out);
        }

        // Captions
        const cap = data.captions || {};
        const layer = document.getElementById("caption-layer");
        if (cap.enabled && Array.isArray(data.cues)) {
          const style = cap.style || "bold";
          layer.classList.add("style-" + style);
          const hi = cap.highlight || "#FFE14D";
          data.cues.forEach(function (c, i) {
            if (c.end <= 0 || c.start >= D) return;
            const cue = document.createElement("div");
            cue.className = "cue";
            cue.id = "cue-" + i;
            cue.style.top = (cap.positionY || 68) + "%";
            cue.style.transform = "translateY(-50%)";
            cue.style.fontSize = (cap.fontSize || 78) + "px";
            const inner = style === "box" ? document.createElement("div") : cue;
            if (inner !== cue) { inner.className = "cue-inner"; cue.appendChild(inner); }
            const text = cap.uppercase ? c.text.toUpperCase() : c.text;
            const tokens = text.split(/\\s+/).filter(Boolean);
            // Word timings: use stored ones when they still match the text, else spread by length.
            let timings = null;
            if (Array.isArray(c.words) && c.words.length === tokens.length) timings = c.words;
            else {
              const total = tokens.reduce(function (n, t) { return n + t.length + 1; }, 0);
              let t = c.start;
              timings = tokens.map(function (tok) {
                const d = ((c.end - c.start) * (tok.length + 1)) / total;
                const w = { start: t, end: t + d };
                t += d;
                return w;
              });
            }
            const spans = tokens.map(function (tok, j) {
              const s = document.createElement("span");
              s.className = "w";
              s.id = "cue-" + i + "-w-" + j;
              s.textContent = tok;
              inner.appendChild(s);
              return s;
            });
            layer.appendChild(cue);

            const start = Math.max(0, c.start);
            const end = Math.min(D, c.end);
            tl.set(cue, { autoAlpha: 1 }, start);
            tl.fromTo(cue, { scale: 0.88 }, { scale: 1, duration: 0.14, ease: "back.out(2.2)" }, start);
            if (style === "bold" || style === "karaoke" || style === "box") {
              const base = style === "karaoke" ? "rgba(255,255,255,0.45)" : "#ffffff";
              const on = style === "karaoke" ? "#ffffff" : hi;
              spans.forEach(function (s, j) {
                const wt = timings[j];
                tl.set(s, { color: on }, Math.max(start, wt.start));
                if (style !== "karaoke") tl.set(s, { color: base }, Math.min(end, Math.max(wt.end, wt.start + 0.05)));
              });
            }
            tl.set(cue, { autoAlpha: 0 }, end);
          });
        }

        window.__timelines = window.__timelines || {};
        window.__timelines["main"] = tl;
        tl.seek(0);
      })();
    </script>
  </body>
</html>
`;
}
